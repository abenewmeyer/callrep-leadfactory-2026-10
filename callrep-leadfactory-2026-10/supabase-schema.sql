-- 1. Profiles (extends auth.users)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text,
  full_name text,
  role text not null default 'subscriber' 
    check (role in ('subscriber', 'sales_rep', 'admin', 'superadmin')),
  sales_rep_id uuid references public.profiles(id),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 2. Leads table (Lead Factory)
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  company_name text,
  owner_name text,
  phone text,
  phone_e164 text,
  phone_type text,
  email text,
  website text,
  trade text,
  city text,
  state text default 'TX',
  county text,
  license_number text,
  source text,
  confidence numeric default 0,
  first_enriched_at timestamptz,
  last_enriched_at timestamptz,
  enrichment_attempts jsonb default '[]'::jsonb,
  enrichment_source text,
  re_enrichment_count int default 0,
  status text default 'new',
  lead_quality_score int default 0,
  notes text,
  -- Future digital suite
  google_biz_status text,
  website_build_status text,
  hosting_status text,
  yelp_status text,
  yellowpages_status text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

