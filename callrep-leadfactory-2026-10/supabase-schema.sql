-- 3. Subscribers
create table if not exists public.subscribers (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid references public.profiles(id),
  stripe_customer_id text,
  stripe_subscription_id text,
  plan text,
  status text default 'active',
  sales_rep_id uuid references public.profiles(id),
  retell_agent_id text,
  phone_number text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 4. Calls
create table if not exists public.calls (
  id uuid primary key default gen_random_uuid(),
  subscriber_id uuid references public.subscribers(id),
  retell_call_id text,
  direction text,
  duration_seconds int,
  summary text,
  recording_url text,
  started_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz default now()
);

-- 5. Support tickets
create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid references public.profiles(id),
  subject text,
  body text,
  status text default 'open',
  created_at timestamptz default now()
);

-- Indexes
create index if not exists idx_leads_trade on public.leads(trade);
create index if not exists idx_leads_state on public.leads(state);
create index if not exists idx_leads_phone_type on public.leads(phone_type);
create index if not exists idx_leads_status on public.leads(status);
create index if not exists idx_subscribers_sales_rep on public.subscribers(sales_rep_id);

-- Enable RLS
alter table public.profiles enable row level security;
alter table public.leads enable row level security;
alter table public.subscribers enable row level security;
alter table public.calls enable row level security;
alter table public.support_tickets enable row level security;

-- Drop old policies if they exist (clean slate)
drop policy if exists "Users can view own profile" on public.profiles;
drop policy if exists "Admins can view all profiles" on public.profiles;
drop policy if exists "Subscribers see only themselves" on public.subscribers;
drop policy if exists "Sales reps see only their sales" on public.subscribers;
drop policy if exists "Admins see all subscribers" on public.subscribers;
drop policy if exists "Own calls only" on public.calls;
drop policy if exists "Authenticated can read leads" on public.leads;
drop policy if exists "Admins can manage leads" on public.leads;

-- Profiles policies
create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Admins can view all profiles" on public.profiles
  for select using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'superadmin'))
  );

-- Subscribers policies
create policy "Subscribers see only themselves" on public.subscribers
  for select using (profile_id = auth.uid());

create policy "Sales reps see only their sales" on public.subscribers
  for select using (sales_rep_id = auth.uid());

create policy "Admins see all subscribers" on public.subscribers
  for select using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'superadmin'))
  );

-- Calls policies
create policy "Own calls only" on public.calls
  for select using (
    subscriber_id in (select id from public.subscribers where profile_id = auth.uid())
    or subscriber_id in (select id from public.subscribers where sales_rep_id = auth.uid())
    or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'superadmin'))
  );

-- Leads policies
create policy "Authenticated can read leads" on public.leads
  for select using (auth.role() = 'authenticated');

create policy "Admins can manage leads" on public.leads
  for all using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'superadmin'))
  );

-- Done
select 'Schema applied successfully' as status;
